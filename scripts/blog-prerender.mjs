// Un link nella protezione si dichiara nel dato ({text, href}) e avvolge la
// sua prima occorrenza nel testo: il testo resta quello dell'array.
function withLink(text, link) {
  const t = esc(text);
  if (!link || !link.text || !link.href) return t;
  const k = esc(link.text);
  const at = t.indexOf(k);
  if (at < 0) throw new Error(`link «${link.text}» assente dal testo`);
  if (!/^\/[a-z0-9\-/]*$/.test(link.href)) throw new Error(`href non interno: ${link.href}`);
  return t.slice(0, at) + '<a href="' + link.href + '">' + k + '</a>' + t.slice(at + k.length);
}

