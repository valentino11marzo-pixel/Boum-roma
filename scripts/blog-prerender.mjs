// scripts/blog-prerender.mjs
// LE GUIDE DEL BLOG SI LEGGONO ANCHE SENZA JAVASCRIPT.
//
// Quattro guide di punta tenevano le loro risposte SOLO dentro un array
// JavaScript: la pagina arrivava al crawler con un contenitore vuoto
// (`<div id="qa-list"></div>`, `<div id="steps-area"></div>`, …) e il testo
// nasceva nel browser. Un motore di risposta che non esegue JS — la maggior
// parte dei crawler AI — vedeva il titolo e nient'altro: le leggi citate, i
// 47 passi, le sette truffe e le dodici zone non esistevano.
//
// Questo script legge i DATI di ogni pagina (e solo quelli: le dichiarazioni
// `scams`/`sevCfg`, `categories`, `phases`, `Z`/`ZO`/`SC`, valutate in un
// contesto node:vm vuoto, senza DOM né globali) e scrive il markup statico,
// con l'HTML escapato, fra i marcatori
//   <!-- PRERENDER:START … -->  …  <!-- PRERENDER:END -->
// dentro il contenitore della lista. Nessun testo e' scritto a mano: ogni
// stringa viene dagli array, quindi pagina e dati non possono divergere —
// e se qualcuno ritocca l'array e dimentica di rilanciare, `--check` (e la
// suite `blogguides`) lo dicono.
//
// Il JS della pagina non ricostruisce piu' la lista: mostra/nasconde e
// apre/chiude i nodi che ci sono gia' (la scam-bible tiene il vecchio ciclo
// solo come ripiego, se il markup statico mancasse).
//
//   node scripts/blog-prerender.mjs [--check]   (--check: non scrive, esce 1 se diverge)
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const R = path.resolve(new URL('..', import.meta.url).pathname);

export const START = '<!-- PRERENDER:START — generated by scripts/blog-prerender.mjs from this page\'s data: edit the data, then run it -->';
export const END = '<!-- PRERENDER:END -->';
const REGION = /<!-- PRERENDER:START[^>]*-->[\s\S]*?<!-- PRERENDER:END -->/g;

export const esc = (v) => String(v)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Il testo dell'inizializzatore di `var|let|const <name> = …` negli <script>
 *  eseguibili della pagina (mai nei JSON-LD), con le parentesi bilanciate e
 *  le stringhe rispettate. */
export function declSource(html, name) {
  const scripts = [...html.matchAll(/<script(?![^>]*\bsrc=)(?![^>]*application\/ld\+json)[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
  const re = new RegExp(`(?:^|[;\\s])(?:var|let|const)\\s+${name}\\s*=\\s*`, 'm');
  for (const src of scripts) {
    const m = re.exec(src);
    if (!m) continue;
    let i = m.index + m[0].length;
    const open = src[i];
    if (open !== '[' && open !== '{') throw new Error(`${name}: inizializzatore non è un letterale ([ o {)`);
    let depth = 0, q = null;
    for (let j = i; j < src.length; j++) {
      const c = src[j];
      if (q) {
        if (c === '\\') { j++; continue; }
        if (c === q) q = null;
        continue;
      }
      if (c === '"' || c === "'" || c === '`') { q = c; continue; }
      if (c === '[' || c === '{') depth++;
      else if (c === ']' || c === '}') {
        depth--;
        if (depth === 0) return src.slice(i, j + 1);
      }
    }
    throw new Error(`${name}: parentesi non chiuse`);
  }
  throw new Error(`${name}: dichiarazione non trovata`);
}

/** Valuta SOLO le dichiarazioni di dati, in un contesto vuoto. */
export function readDecls(html, names) {
  const out = {};
  for (const n of names) {
    out[n] = vm.runInNewContext('(' + declSource(html, n) + ')', {}, { timeout: 1000 });
  }
  return out;
}

