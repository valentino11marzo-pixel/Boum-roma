export const PAGES = {
  'blog-scam-bible.html': { names: ['scams', 'sevCfg'], render: scamBible },
  'blog-tenant-rights.html': { names: ['categories'], render: tenantRights },
  'blog-47-steps.html': { names: ['phases'], render: fortySeven },
  'blog-neighborhood-guide.html': { names: ['Z', 'ZO', 'SC'], render: neighborhoods },
};

export function dataOf(file, html) {
  return readDecls(html, PAGES[file].names);
}

export function markup(file, html) {
  return PAGES[file].render(dataOf(file, html));
}

export function rebuild(file, html) {
  const regions = html.match(REGION) || [];
  if (regions.length !== 1) throw new Error(`${file}: attesi 1 blocco PRERENDER, trovati ${regions.length}`);
  const body = markup(file, html);
  return html.replace(REGION, () => START + '\n' + body + '\n' + END);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const CHECK = process.argv.includes('--check');
  let bad = 0;
  for (const f of Object.keys(PAGES)) {
    const p = path.join(R, f);
    const s = fs.readFileSync(p, 'utf8');
    let out;
    try { out = rebuild(f, s); } catch (e) { console.log(`✗ ${f}: ${e.message}`); bad++; continue; }
    if (out === s) { console.log(`✓ ${f}: già allineato`); continue; }
    if (CHECK) { console.log(`✗ ${f}: il markup statico non corrisponde ai dati — rilancia node scripts/blog-prerender.mjs`); bad++; continue; }
    fs.writeFileSync(p, out);
    console.log(`✎ ${f}: markup statico rigenerato`);
  }
  process.exit(bad ? 1 : 0);
}
