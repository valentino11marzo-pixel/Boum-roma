#!/usr/bin/env node
// build-cities.mjs — the BOOM city pages, built from data. Zero dependencies.
//
//   node build-cities.mjs           regenerate /<slug>.html from cities/<slug>.json
//   node build-cities.mjs --check   exit 1 when a committed page is not what the build makes
//
// Contract: BOOM_CITIES_BRIEF.md. One template (cities/_template.html), one
// shared file (cities/_shared.json: domain + legal entity, identical on every
// page), one JSON per city. The generated pages are committed because Vercel
// serves the repo as-is (no build step).
//
// Token syntax in the template: {{a.b}} prints the value HTML-escaped,
// {{{a.b}}} prints it raw. In the city JSON a field whose name ends in `Html`
// is trusted markup; every other field is escaped. Arrays (stats, steps,
// plans, checks, faq, …) are rendered by the small functions below.
//
// The build refuses, instead of printing something wrong:
//   - a token with no value (a missing field never becomes an empty string);
//   - a city with `live: true` that still carries placeholders: bracketed
//     copy like [NAME], config values like REPLACE_ME / 39XXXXXXXXXX, or a
//     stat without a source (§5.3: stats without a source don't ship);
//   - `mode: "waitlist"` — not built yet (Phase 3): this template prints
//     prices and a Stripe link, which a waitlist page must never show;
//   - overwriting a root .html it did not generate (a slug like "index"
//     would otherwise replace the homepage).
// A city with `live: false` builds, carries <meta name="robots"
// content="noindex">, and the placeholders are listed so nothing is forgotten.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
export const GENERATED_MARK = 'GENERATED by build-cities.mjs';

export class BuildError extends Error {}

export const esc = (v) => String(v)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// €1,500 — deterministic thousands, never toLocaleString (small-ICU runtimes
// degrade it silently: the lesson already paid on /executive).
export const eur = (n) => '€' + String(Math.round(Number(n))).replace(/\B(?=(\d{3})+(?!\d))/g, ',');

// JSON inside <script>: `<` escaped so a value can never close the tag.
const scriptJson = (obj, indent) => JSON.stringify(obj, null, 2)
  .replace(/</g, '\\u003c')
  .split('\n').map((l, i) => (i ? indent + l : l)).join('\n');

const get = (obj, dotted) => dotted.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj);

export function fill(template, data, where) {
  const missing = new Set();
  const out = template.replace(/\{\{\{\s*([\w.]+)\s*\}\}\}|\{\{\s*([\w.]+)\s*\}\}/g, (m, raw, plain) => {
    const key = raw || plain;
    const v = get(data, key);
    if (v === undefined || v === null || typeof v === 'object') { missing.add(key); return m; }
    return raw ? String(v) : esc(v);
  });
  if (missing.size) throw new BuildError(`${where}: unresolved tokens: ${[...missing].join(', ')}`);
  const left = out.match(/\{\{[^}]*\}\}/g);
  if (left) throw new BuildError(`${where}: malformed tokens left in the output: ${[...new Set(left)].join(', ')}`);
  return out;
}

function need(cond, where, msg) { if (!cond) throw new BuildError(`${where}: ${msg}`); }
const list = (city, dotted) => {
  const v = get(city, dotted);
  need(Array.isArray(v) && v.length, `cities/${city.slug}.json`, `${dotted} must be a non-empty array`);
  return v;
};

// ── the array renderers ────────────────────────────────────────────────────
const R = {
  stats: (c) => list(c, 'problem.stats').map((s) =>
    `      <div class="stat"><div class="n">${esc(s.n)}</div><div class="l">${esc(s.l)}</div></div>`).join('\n'),

  legal: (c) => list(c, 'agent.legalHtml').map((p) => `      <p>${p}</p>`).join('\n'),

  steps: (c) => list(c, 'how.steps').map((s, i) =>
    `      <div class="step reveal"><div class="k">${String(i + 1).padStart(2, '0')}</div><div><h3>${esc(s.title)}</h3><p>${esc(s.text)}</p></div></div>`).join('\n'),

  plans: (c) => list(c, 'pricing.plans').map((p) => [
    `      <div class="plan${p.featured ? ' featured' : ''} reveal">`,
    `        <div class="tag">${esc(p.tag)}</div>`,
    `        <h3>${esc(p.title)}</h3>`,
    `        <div class="sub">${esc(p.sub)}</div>`,
    `        <div class="price"><span class="now">${eur(p.price)}</span>${p.per ? `<span class="per">${esc(p.per)}</span>` : ''}</div>`,
    `        <div class="note">${esc(p.note)}</div>`,
    '        <ul>',
    ...p.items.map((it) => `          <li>${esc(it)}</li>`),
    '        </ul>',
    `        <a class="btn btn-${p.cta.style === 'gold' ? 'gold' : 'ghost'}" href="#reserve" data-plan="${esc(p.name)}">${esc(p.cta.label)}</a>`,
    '      </div>'
  ].join('\n')).join('\n\n'),

  checks: (c) => list(c, 'checks.items').map((k) =>
    `      <div class="card reveal"><h3>${esc(k.title)}</h3><p>${esc(k.text)}</p></div>`).join('\n'),

  person: (c) => list(c, 'person.paragraphs').map((p) => `        <p>${esc(p)}</p>`).join('\n'),

  testimonials: (c) => list(c, 'proof.testimonials').map((t) =>
    `      <blockquote>${t.placeholder ? `<span class="ph">${esc(t.quote)}</span>` : esc(t.quote)}<footer>— ${esc(t.by)}</footer></blockquote>`).join('\n'),

  faq: (c) => list(c, 'faq.items').map((f) =>
    `    <details><summary>${esc(f.q)}</summary><p>${esc(f.a)}</p></details>`).join('\n'),

  serviceOptions: (c) => list(c, 'reserve.serviceOptions').map((name) => {
    const plan = c.pricing.plans.find((p) => p.name === name);
    need(plan, `cities/${c.slug}.json`, `reserve.serviceOptions names "${name}", which is not a plan`);
    return `              <option value="${esc(name)}">${esc(name)} — ${eur(plan.price)}</option>`;
  }).join('\n'),

  budgetOptions: (c) => list(c, 'reserve.budgetOptions').map((o) => `              <option>${esc(o)}</option>`).join('\n')
};

// ── JSON-LD: one Organization (shared), the Service with its Offers, the FAQ.
// The FAQ answers are the visible answers, word for word: a schema that says
// something the page doesn't show is hidden content (tests/seo, rule FAQ).
function jsonLd(c, shared, pageUrl) {
  const site = shared.siteUrl;
  const o = shared.organization;
  const orgId = site + '/#organization';
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'Organization', '@id': orgId, name: o.name, legalName: o.legalName, url: site,
        founder: o.founder, address: o.address, vatID: o.vatID, description: o.description, areaServed: o.areaServed
      },
      {
        '@type': 'Service', '@id': pageUrl + '#service', name: c.service.name, serviceType: c.service.serviceType,
        provider: { '@id': orgId }, areaServed: { '@type': 'City', name: c.city },
        audience: { '@type': 'Audience', audienceType: c.service.audience }, url: pageUrl,
        offers: c.pricing.plans.map((p) => ({
          '@type': 'Offer', name: p.name, price: String(p.price), priceCurrency: 'EUR',
          description: p.offerDescription || p.sub
        }))
      },
      {
        '@type': 'FAQPage',
        mainEntity: c.faq.items.map((f) => ({
          '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a }
        }))
      }
    ]
  };
}

// What must be replaced before a page may go live. Bracketed copy is found in
// the VISIBLE text (scripts and styles removed, tags turned into spaces, so
// "[PHOTO OF<br>LOCAL OPERATOR]" is caught too).
export function findPlaceholders(html, city) {
  const found = [];
  const text = html
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ');
  for (const m of text.matchAll(/\[[^\[\]]{1,300}\]/g)) found.push(m[0].replace(/\s+/g, ' ').trim());
  for (const [k, v] of Object.entries(city.config || {})) {
    if (typeof v === 'string' && /REPLACE|X{4,}/.test(v)) found.push(`config.${k} = ${v}`);
  }
  ((city.problem && city.problem.stats) || []).forEach((s, i) => {
    if (!(s.source && s.source.url && s.source.date)) found.push(`problem.stats[${i}] "${s.n}" has no source {url, date}`);
  });
  return [...new Set(found)];
}

export function renderCity({ template, shared, city, assetVersion }) {
  const where = `cities/${city.slug}.json`;
  need(/^[a-z0-9-]+$/.test(city.slug || ''), where, 'slug must be lowercase letters, digits and dashes');
  need(typeof city.live === 'boolean', where, '"live" must be true or false');
  need(city.mode === 'deposit' || city.mode === 'waitlist', where, '"mode" must be "deposit" or "waitlist"');
  need(city.mode === 'deposit', where,
    'mode "waitlist" is not built yet (Phase 3): this template prints prices and a Stripe link, which a waitlist page must never show');

  const site = shared.siteUrl;
  need(/^https:\/\/[^/]+$/.test(site || ''), 'cities/_shared.json', 'siteUrl must be https://host with no trailing slash');
  const pageUrl = `${site}/${city.slug}`;
  const cfg = city.config || {};
  need(cfg.WHATSAPP && cfg.WA_MESSAGE, where, 'config.WHATSAPP and config.WA_MESSAGE are required');
  const config = { ...cfg, MODE: city.mode, CITY: city.city, SITE_URL: site };

  const data = {
    ...city,
    config,
    entity: shared.entity,
    siteUrl: site,
    siteHost: new URL(site).hostname.replace(/^www\./, ''),
    pageUrl,
    waUrl: `https://wa.me/${cfg.WHATSAPP}?text=${encodeURIComponent(cfg.WA_MESSAGE)}`,
    robotsMeta: city.live ? '' : '<meta name="robots" content="noindex">',
    jsonLd: scriptJson(jsonLd(city, shared, pageUrl), ''),
    configJson: scriptJson(config, '  '),
    assetVersion,
    statsHtml: R.stats(city),
    legalHtml: R.legal(city),
    stepsHtml: R.steps(city),
    plansHtml: R.plans(city),
    checksHtml: R.checks(city),
    personHtml: R.person(city),
    testimonialsHtml: R.testimonials(city),
    faqHtml: R.faq(city),
    serviceOptionsHtml: R.serviceOptions(city),
    budgetOptionsHtml: R.budgetOptions(city)
  };

  const html = fill(template, data, where);

  // The JSON-LD that landed in the page must parse: the build fails otherwise.
  for (const m of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    try { JSON.parse(m[1]); } catch (e) { throw new BuildError(`${where}: JSON-LD does not parse: ${e.message}`); }
  }

  const placeholders = findPlaceholders(html, city);
  if (city.live && placeholders.length) {
    throw new BuildError(`${where} is live:true but still has ${placeholders.length} placeholder(s):\n    - `
      + placeholders.join('\n    - '));
  }
  return { slug: city.slug, file: `${city.slug}.html`, live: city.live, mode: city.mode, html, placeholders };
}

function readJson(file) {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); }
  catch (e) { throw new BuildError(`${path.relative(ROOT, file) || file}: ${e.message}`); }
}
const hash = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex').slice(0, 10);

export function buildAll({ root = ROOT } = {}) {
  const dir = path.join(root, 'cities');
  const template = fs.readFileSync(path.join(dir, '_template.html'), 'utf8');
  const shared = readJson(path.join(dir, '_shared.json'));
  const assetVersion = {
    css: hash(path.join(root, 'assets/boom-city.css')),
    js: hash(path.join(root, 'assets/boom-city.js'))
  };
  return fs.readdirSync(dir)
    .filter((f) => f.endsWith('.json') && !f.startsWith('_'))
    .sort()
    .map((f) => {
      const city = readJson(path.join(dir, f));
      need(city.slug === f.replace(/\.json$/, ''), `cities/${f}`, `slug "${city.slug}" must match the file name`);
      return renderCity({ template, shared, city, assetVersion });
    });
}

// Writes (or, with check, compares) every page. Every page is validated
// before the first byte is written: one bad city leaves the others untouched.
export function writeAll({ root = ROOT, check = false } = {}) {
  const pages = buildAll({ root });
  const results = pages.map((p) => {
    const out = path.join(root, p.file);
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
    if (cur !== null && !cur.includes(GENERATED_MARK)) {
      throw new BuildError(`${p.file} exists and was not generated by this script — refusing to overwrite it`);
    }
    return { ...p, out, stale: cur !== p.html };
  });
  if (!check) for (const r of results) if (r.stale) fs.writeFileSync(r.out, r.html);
  return results;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes('--check');
  try {
    let stale = 0;
    for (const p of writeAll({ check })) {
      if (check && p.stale) { stale++; console.error(`✗ ${p.file} is stale — run: npm run build:cities`); continue; }
      console.log(`${check ? '✓ up to date' : '✓ built'}  ${p.file}  ·  ${p.live ? 'LIVE' : 'draft (noindex)'}  ·  mode ${p.mode}`);
      if (p.placeholders.length) {
        console.log(`  ${p.placeholders.length} placeholder(s) to replace before live:true:`);
        for (const x of p.placeholders) console.log('   - ' + x);
      }
    }
    if (stale) process.exit(1);
  } catch (e) {
    if (e instanceof BuildError) { console.error('✗ ' + e.message); process.exit(1); }
    throw e;
  }
}
