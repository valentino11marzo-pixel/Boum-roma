// ── JSON-LD: Organization (shared) + WebPage (speakable) + Service with its
// Offers + FAQ. The FAQ answers are the visible answers, word for word: a
// schema that says something the page doesn't show is hidden content
// (tests/seo, rule FAQ). Breadcrumb in its own block, as on every page.
function jsonLdBreadcrumb(c, shared, pageUrl) {
  return {
    '@context': 'https://schema.org', '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home', item: shared.siteUrl + '/' },
      { '@type': 'ListItem', position: 2, name: c.city, item: pageUrl }
    ]
  };
}
function jsonLd(c, shared, pageUrl, ogImage) {
  const site = shared.siteUrl;
  const o = shared.organization;
  const orgId = site + '/#organization';
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'Organization', '@id': orgId, name: o.name, legalName: o.legalName, url: site, logo: o.logo,
        founder: o.founder, address: o.address, vatID: o.vatID, contactPoint: o.contactPoint,
        description: o.description, areaServed: o.areaServed, availableLanguage: ['en', 'it']
      },
      {
        '@type': 'WebPage', '@id': pageUrl + '#page', url: pageUrl, name: c.meta.ogTitle, inLanguage: 'en',
        isPartOf: { '@id': site + '/#website' }, about: { '@id': orgId },
        primaryImageOfPage: { '@type': 'ImageObject', url: ogImage, width: 1200, height: 630 },
        speakable: { '@type': 'SpeakableSpecification', cssSelector: ['.hero .sub', '.enbref'] }
      },
      {
        '@type': 'Service', '@id': pageUrl + '#service', name: c.service.name, serviceType: c.service.serviceType,
        description: c.service.description, provider: { '@id': orgId },
        areaServed: { '@type': 'City', name: c.city },
        audience: { '@type': 'Audience', audienceType: c.service.audience },
        availableLanguage: ['en'], url: pageUrl,
        // Offers only where a price is sold (BOOM_CITIES_BRIEF.md §8): a
        // waitlist Service carries no price, in the schema as on the page.
        ...(c.mode === 'search' ? {
          offers: c.pricing.plans.map((p) => ({
            '@type': 'Offer', name: p.label, price: String(p.price), priceCurrency: 'EUR',
            description: p.offerDescription || p.text
          }))
        } : {})
      },
      {
        '@type': 'FAQPage', inLanguage: 'en',
        mainEntity: c.faq.items.map((f) => ({
          '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a }
        }))
      }
    ]
  };
}

// What must be replaced before a page may go live. Bracketed copy is found in
// the VISIBLE text (scripts and styles removed, tags turned into spaces).
export function findPlaceholders(html, city, { root = ROOT } = {}) {
  const found = [];
  const text = html
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ');
  for (const m of text.matchAll(/\[[^\[\]]{1,300}\]/g)) found.push(m[0].replace(/\s+/g, ' ').trim());
  for (const [k, v] of Object.entries(city.config || {})) {
    if (typeof v === 'string' && /REPLACE|X{4,}/.test(v)) found.push(`config.${k} = ${v}`);
  }
  if (city.slug && !fs.existsSync(path.join(root, `og-${city.slug}.png`))) {
    found.push(`og-${city.slug}.png is missing (python3 design/pages-deco/genera-og-cities.py)`);
  }
  return [...new Set(found)];
}

// The two fragments every public page inlines, read from their single source.
export function fragments(root = ROOT) {
  const scrollCss = fs.readFileSync(path.join(root, 'css/boom-scroll.css'), 'utf8');
  const scrollJs = fs.readFileSync(path.join(root, 'js/boom-scroll.js'), 'utf8');
  const solari = fs.readFileSync(path.join(root, 'design/pages-deco/solari-engine.html'), 'utf8');
  need(/window\.BoomSolari\s*=/.test(solari) && /\.fc2\s*\{/.test(solari), 'design/pages-deco/solari-engine.html',
    'is not the Solari engine fragment (expected the .fc2 cell CSS and window.BoomSolari)');
  return {
    scrollBlock: `<!-- BOOM_SCROLL:START -->\n<style>\n${scrollCss}</style>\n<script>\n${scrollJs}</script>\n<!-- BOOM_SCROLL:END -->`,
    solariEngine: solari.trimEnd()
  };
}

export function renderCity({ template, shared, city, assetVersion, frags, root = ROOT, cities = [city] }) {
  const where = `cities/${city.slug}.json`;
  need(/^[a-z0-9-]+$/.test(city.slug || ''), where, 'slug must be lowercase letters, digits and dashes');
  need(typeof city.live === 'boolean', where, '"live" must be true or false');
  need(city.mode === 'search' || city.mode === 'waitlist', where, '"mode" must be "search" or "waitlist"');
  need(typeof city.city === 'string' && city.city.trim(), where, '"city" is required');
  const waitlist = city.mode === 'waitlist';

  const site = shared.siteUrl;
  need(/^https:\/\/[^/]+$/.test(site || ''), 'cities/_shared.json', 'siteUrl must be https://host with no trailing slash');
  need(shared.contact && /^\d{8,15}$/.test(shared.contact.whatsapp || '') && /@/.test(shared.contact.email || ''),
    'cities/_shared.json', 'contact.whatsapp (digits only) and contact.email are required');
  const pageUrl = `${site}/${city.slug}`;
  const ogImage = `${site}/og-${city.slug}.png`;

  const plans = list(city, 'pricing.plans');
  const ids = new Set();
  for (const p of plans) {
    need(/^[a-z0-9-]+$/.test(p.id || '') && !ids.has(p.id), where, `plan id "${p.id}" must be unique, lowercase and dashed`);
    ids.add(p.id);
    need(p.label && p.se && p.name && p.text && p.cta, where, `plan "${p.id}" needs label, se, name, text, cta`);
    need(Array.isArray(p.includes) && p.includes.length >= 2 && p.includes.length <= 5 && p.includes.every((x) => typeof x === 'string' && x.trim()),
      where, `plan "${p.id}" needs includes: 2–5 lines of what the fee buys`);
    if (waitlist) {
      need(p.price === undefined && p.per === undefined && p.offerDescription === undefined, where,
        `plan "${p.id}": a waitlist city carries no price, per or offerDescription (BOOM_CITIES_BRIEF.md §4 — fees arrive with the registered partner)`);
    } else {
      need(p.per, where, `plan "${p.id}" needs label, se, name, text, per, cta`);
      need(Number.isFinite(Number(p.price)) && Number(p.price) > 0, where, `plan "${p.id}" needs a positive price`);
    }
  }

  // The board word: the city, letters only, upper-case — the drum has no
  // accents or spaces (the Solari engine's own alphabet).
  const word = String(city.word || city.city).toUpperCase().normalize('NFD').replace(/[^A-Z]/g, '');
  need(word.length >= 2 && word.length <= 12, where, `board word "${word}" must be 2–12 letters (override with "word")`);

  const cfg = city.config || {};
  const config = {
    SLUG: city.slug, CITY: city.city, WORD: word, MODE: city.mode,
    LEAD_ENDPOINT: '/api/city-lead', SITE_URL: site,
    WHATSAPP: cfg.WHATSAPP || shared.contact.whatsapp, EMAIL: cfg.EMAIL || shared.contact.email
  };

  const data = {
    ...city,
    config,
    word,
    wordEm: (word.length * CELL_EM).toFixed(2),
    entity: shared.entity,
    contact: { ...shared.contact, whatsapp: config.WHATSAPP, email: config.EMAIL },
    siteUrl: site,
    pageUrl,
    ogImage,
    year: String(new Date().getUTCFullYear()),
    robotsMeta: city.live
      ? '<meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1">'
      : '<meta name="robots" content="noindex">',
    jsonLdBreadcrumb: scriptJson(jsonLdBreadcrumb(city, shared, pageUrl), ''),
    jsonLd: scriptJson(jsonLd(city, shared, pageUrl, ogImage), ''),
    configJson: scriptJson(config, '  '),
    assetVersion,
    scrollBlock: frags.scrollBlock,
    solariEngine: frags.solariEngine,
    familyHtml: R.family(familyFor(city, cities, shared)),
    trustHtml: R.trust(city),
    budgetOptionsHtml: R.budgetOptions(city),
    serviceChipsHtml: R.serviceChips(city),
    machineItemsHtml: R.machineItems(city),
    stepsHtml: R.steps(city),
    tlineHtml: R.tline(city),
    plansHtml: R.plans(city),
    flowsHtml: R.flows(city),
    flagsHtml: R.flags(city),
    brefHtml: R.bref(city, shared, pageUrl),
    faqHtml: R.faq(city),
    footerBoomHtml: R.footerBoom(shared)
  };

  const html = fill(template, data, where);

  // The JSON-LD that landed in the page must parse: the build fails otherwise.
  for (const m of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
    try { JSON.parse(m[1]); } catch (e) { throw new BuildError(`${where}: JSON-LD does not parse: ${e.message}`); }
  }
  // The guard the whole file is for: the gold of the public site, never the portal's.
  need(!/#D4AF37/i.test(html), where, 'the public pages use #FFD700 (boom-2026.css); #D4AF37 is the portal gold');
  // A waitlist page shows no price anywhere — visible text, boards, schema
  // (BOOM_CITIES_BRIEF.md §10). The client's own budget bands in the <select>
  // are theirs, not ours: they are the one place a € may stand.
  if (waitlist) {
    const visible = html
      .replace(/<script[\s\S]*?<\/script>/gi, ' ').replace(/<style[\s\S]*?<\/style>/gi, ' ')
      .replace(/<select[\s\S]*?<\/select>/gi, ' ').replace(/<[^>]+>/g, ' ');
    const priced = visible.match(/€\s?\d[\d.,]*|\d[\d.,]*\s?€/);
    need(!priced, where, `a waitlist page prints no price, found "${priced && priced[0]}"`);
    need(!/flap-prezzo|data-p="/.test(html), where, 'a waitlist page mounts no price board');
    for (const m of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
      need(!/"price"|"offers"|"priceCurrency"/.test(m[1]), where, 'a waitlist page declares no Offer and no price in its JSON-LD');
    }
    need(!/stripe/i.test(html), where, 'a waitlist page carries no Stripe link');
  }

  const placeholders = findPlaceholders(html, city, { root });
  if (city.live && placeholders.length) {
    throw new BuildError(`${where} is live:true but still has ${placeholders.length} placeholder(s):\n    - `
      + placeholders.join('\n    - '));
  }
  return { slug: city.slug, file: `${city.slug}.html`, live: city.live, mode: city.mode, html, placeholders };
}

function readJson(file) {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); }
  catch (e) { throw new BuildError(`${path.relative(ROOT, file) || file}: ${e.message}`); }
}
const hash = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex').slice(0, 10);

export function buildAll({ root = ROOT } = {}) {
  const dir = path.join(root, 'cities');
  const template = fs.readFileSync(path.join(dir, '_template.html'), 'utf8');
  const shared = readJson(path.join(dir, '_shared.json'));
  const assetVersion = {
    css: hash(path.join(root, 'assets/boom-city.css')),
    js: hash(path.join(root, 'assets/boom-city.js'))
  };
  const frags = fragments(root);
  // Every city is read before any is rendered: the family strip of one page
  // is made of the others.
  const cities = fs.readdirSync(dir)
    .filter((f) => f.endsWith('.json') && !f.startsWith('_'))
    .sort()
    .map((f) => {
      const city = readJson(path.join(dir, f));
      need(city.slug === f.replace(/\.json$/, ''), `cities/${f}`, `slug "${city.slug}" must match the file name`);
      return city;
    });
  return cities.map((city) => renderCity({ template, shared, city, assetVersion, frags, root, cities }));
}

// Writes (or, with check, compares) every page. Every page is validated
// before the first byte is written: one bad city leaves the others untouched.
export function writeAll({ root = ROOT, check = false } = {}) {
  const pages = buildAll({ root });
  const results = pages.map((p) => {
    const out = path.join(root, p.file);
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
    if (cur !== null && !cur.includes(GENERATED_MARK)) {
      throw new BuildError(`${p.file} exists and was not generated by this script — refusing to overwrite it`);
    }
    return { ...p, out, stale: cur !== p.html };
  });
  if (!check) for (const r of results) if (r.stale) fs.writeFileSync(r.out, r.html);
  return results;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes('--check');
  try {
    let stale = 0;
    for (const p of writeAll({ check })) {
      if (check && p.stale) { stale++; console.error(`✗ ${p.file} is stale — run: npm run build:cities`); continue; }
      console.log(`${check ? '✓ up to date' : '✓ built'}  ${p.file}  ·  ${p.live ? 'LIVE' : 'draft (noindex)'}  ·  mode ${p.mode}`);
      if (p.placeholders.length) {
        console.log(`  ${p.placeholders.length} placeholder(s) to replace before live:true:`);
        for (const x of p.placeholders) console.log('   - ' + x);
      }
    }
    if (stale) process.exit(1);
  } catch (e) {
    if (e instanceof BuildError) { console.error('✗ ' + e.message); process.exit(1); }
    throw e;
  }
}
