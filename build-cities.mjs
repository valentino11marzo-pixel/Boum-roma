// Contract: BOOM_CITIES_BRIEF.md (v1.5, 26/10 — «Il biglietto»: the study
// in STUDIO_CITIES_ESPERIENZA.md §12). One template (cities/_template.html),
// one shared file (cities/_shared.json: domain, legal entity, contacts, the
