#!/usr/bin/env node
// build-cities.mjs — the BOOM city pages, built from data. Zero dependencies.
//
//   node build-cities.mjs           regenerate /<slug>.html from cities/<slug>.json
//   node build-cities.mjs --check   exit 1 when a committed page is not what the build makes
//
// Contract: BOOM_CITIES_BRIEF.md. One template (cities/_template.html), one
// shared file (cities/_shared.json: domain, legal entity, contacts — identical
// on every page), one JSON per city. The generated pages are committed because
// Vercel serves the repo as-is (no build step).
//
// The page is a BOOM 2026 page: css/boom-2026.css + the city layer
// assets/boom-city.css, gold #FFD700, the Executive v4 conversion grammar
// (one door, the form in the hero, ≤8 blocks) and the Solari split-flap
// engine of index.html/apartments.html INLINED from its single source
// (design/pages-deco/solari-engine.html) — the city name on the board in
// the title, the prices on the board in the plates. The scroll contract
// (css/boom-scroll.css + js/boom-scroll.js) is inlined the same way, between
// the same markers every public page carries.
//
// Token syntax in the template: {{a.b}} prints the value HTML-escaped,
// {{{a.b}}} prints it raw. In the city JSON a field whose name ends in `Html`
// is trusted markup; every other field is escaped. Arrays (steps, plans,
// checks, faq, …) are rendered by the small functions below.
//
// The build refuses, instead of printing something wrong:
//   - a token with no value (a missing field never becomes an empty string);
//   - a city with `live: true` that still carries placeholders — bracketed
//     copy like [NAME], config values like REPLACE_ME / 39XXXXXXXXXX, or an
//     og-<slug>.png that does not exist on disk (a card that 404s on every
//     WhatsApp forward: the exact defect tests/seo was built to catch);
//   - a `mode: "waitlist"` city (Barcelona, Paris — BOOM_CITIES_BRIEF.md §4:
//     no intermediation in Catalonia without AICAT registration, carte
//     professionnelle in France) that carries a price anywhere: in its plans,
//     in its copy, in the chips, in the JSON-LD. The waitlist page describes
//     the three services and opens the file; the prices arrive with the
//     registered partner. A `mode: "search"` city without prices is refused
//     the same way: the two modes cannot blur;
//   - overwriting a root .html it did not generate (a slug like "index"
//     would otherwise replace the homepage).
// A city with `live: false` builds, carries <meta name="robots"
// content="noindex">, and the placeholders are listed so nothing is forgotten.

