export class BuildError extends Error {}

export const esc = (v) => String(v)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// €1,500 — deterministic thousands, never toLocaleString (small-ICU runtimes
