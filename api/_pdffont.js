// api/_pdffont.js — THE FONT OF THE ORDER DOCUMENTS: the client's name
// printed as the client typed it (v1.8, review finding F4).
//
// The order PDF of a desk that charges at signing (api/_cityorderpdf.js) is
// the contract copy: Paris's numbered search mandate (its only French copy)
// and Berlin's search order, and the order keeps its SHA-256. Its body was
// set in pdf-lib's standard Helvetica, which knows WinAnsi only — and
// api/_pdfbrand.js wa() quietly deleted every other letter: «Ayşe Yılmaz»
// came out «Aye Ylmaz», «Łukasz Wiśniewski» «ukasz Winiewski», «Tomáš
// Dvořák» «Tomá Dvoák», a Cyrillic name vanished from the party line.
//
// The body is now set in BOOM Doc Sans, a subset of Liberation Sans (the
// metrics of Arial, hence of Helvetica: the lines break where they did),
// generated by design/pages-deco/genera-font-pdf.py into
// api/_pdffont-data.js: Latin with every extension, Greek and Cyrillic.
// pdf-lib embeds it through its fontkit interface, which this file
// implements on the metrics fontTools computed at generation: no fontkit
// dependency (its import alone costs ~150 ms of cold start on the checkout
// function), no font table read at runtime. The masthead, the title and the
// legal footer keep the Helvetica of api/_pdfbrand.js: they carry fixed text.
//
// What the font cannot print (a Chinese, Arabic or Hebrew name, an emoji) is
// never deleted in silence: printable() prints «?» in its place, returns the
// characters it could not print, and the order records them and tells the
// operator (api/_cityorder.js, agentNotifications/book-pdf-<id>). A
// compatibility form whose decomposition prints (a full-width «Ａ», the «ﬁ»
// ligature) prints as that decomposition: the same text, not a loss.

import crypto from 'node:crypto';
import { FONT } from './_pdffont-data.js';

export const FONT_NAME = FONT.name;

// the cmap: runs [firstCodePoint, lastCodePoint, firstGlyphId], sorted
const RUNS = FONT.cmap;
/** The glyph id of a code point in the document font; 0 (.notdef) when it has none. */
export function glyphIdOf(cp) {
  let lo = 0, hi = RUNS.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1, r = RUNS[mid];
    if (cp < r[0]) hi = mid - 1;
    else if (cp > r[1]) lo = mid + 1;
    else return r[2] + (cp - r[0]);
  }
  return 0;
}
/** Does the document font print this code point? */
export const printsChar = (cp) => glyphIdOf(cp) > 0;

/**
 * The text as the document font can print it. NFC first (a name typed with
 * combining marks gets its precomposed letters); a character the font has
 * stays; a compatibility form whose NFKD decomposition prints becomes that
 * decomposition; anything else becomes «?» and is reported.
 * @returns {{ text: string, lost: string[] }} lost = the distinct characters printed as «?»
 */
export function printable(s) {
  let text = '';
  const lost = [];
  for (const ch of String(s == null ? '' : s).normalize('NFC')) {
    if (printsChar(ch.codePointAt(0))) { text += ch; continue; }
    const k = ch.normalize('NFKD');
    if (k !== ch && [...k].every((c) => printsChar(c.codePointAt(0)))) { text += k; continue; }
    text += '?';
    if (!lost.includes(ch)) lost.push(ch);
  }
  return { text, lost };
}

// the font file, decoded once and checked against the hash the generator
// wrote: a damaged edit of the data module fails loudly, never a PDF with
// garbage glyphs
let BYTES = null;
export function fontBytes() {
  if (!BYTES) {
    const b = Buffer.from(FONT.ttf, 'base64');
    if (crypto.createHash('sha256').update(b).digest('hex') !== FONT.sha256) {
      throw Object.assign(new Error('pdffont: the document font does not match its hash'), { code: 'font_corrupt' });
    }
    BYTES = new Uint8Array(b);
  }
  return BYTES;
}

// ── the fontkit interface pdf-lib's CustomFontEmbedder reads (subset:false):
// create(bytes) → a font with its metrics, characterSet, glyphForCodePoint
// and layout(text).glyphs [{ id, advanceWidth, codePoints }]. One glyph per
// character (the generator refuses a font where two characters share one):
// the ToUnicode map pdf-lib writes from codePoints gives the text back.
const glyphs = new Map();
function glyphOf(cp) {
  const id = glyphIdOf(cp);
  let g = glyphs.get(id);
  if (!g) {
    g = Object.freeze({ id, advanceWidth: FONT.widths[id] || 0, codePoints: id ? [cp] : [] });
    glyphs.set(id, g);
  }
  return g;
}
let CHARSET = null;
const DOC_FONT = Object.freeze({
  postscriptName: FONT.name,
  unitsPerEm: FONT.unitsPerEm,
  ascent: FONT.ascent,
  descent: FONT.descent,
  capHeight: FONT.capHeight,
  xHeight: FONT.xHeight,
  italicAngle: FONT.italicAngle,
  bbox: Object.freeze({ minX: FONT.bbox[0], minY: FONT.bbox[1], maxX: FONT.bbox[2], maxY: FONT.bbox[3] }),
  cff: null,                                   // TrueType outlines: FontFile2, CIDFontType2
  'OS/2': Object.freeze({ sFamilyClass: FONT.familyClass }),
  post: Object.freeze({ isFixedPitch: FONT.fixedPitch }),
  head: Object.freeze({ macStyle: Object.freeze({ italic: FONT.italic }) }),
  get characterSet() {
    if (!CHARSET) {
      CHARSET = [];
      for (const [a, b] of RUNS) for (let cp = a; cp <= b; cp++) CHARSET.push(cp);
    }
    return CHARSET;
  },
  glyphForCodePoint: glyphOf,
  hasGlyphForCodePoint: printsChar,
  layout(text) {
    const out = [];
    for (const ch of String(text)) out.push(glyphOf(ch.codePointAt(0)));
    return { glyphs: out, positions: [] };
  },
});
/** Pass to PDFDocument.registerFontkit(), then embedFont(fontBytes(), { subset: false, customName: FONT_NAME }). */
export const DOC_FONTKIT = Object.freeze({ create: () => DOC_FONT });
